import assert from 'node:assert/strict';
import fs from 'node:fs';
import {chooseDetailedCars, npcWheelPose} from './npc-detail-state.mjs';
const eye = {x: 0, y: 0, z: 0};
const cars = [1, 2, 3, 4].map(id => ({id, x: id * 10, y: 0}));
assert.deepEqual([...chooseDetailedCars(cars, eye)], [1, 2]);
assert.deepEqual([...chooseDetailedCars(cars, eye, new Set(), true)], [1]);
assert.equal(chooseDetailedCars(cars, {...eye, z: 150}).size, 0, 'Aerial view must not pay near-mesh cost');
assert.equal(chooseDetailedCars(cars, {...eye, x: NaN}).size, 0);
assert.deepEqual([...chooseDetailedCars([{id: 1, x: 47, y: 0}], eye, new Set([1]))], [1]);
assert.equal(chooseDetailedCars([{id: 1, x: 53, y: 0}], eye, new Set([1])).size, 0);
assert.deepEqual([...chooseDetailedCars([{id: 1, x: 20, y: 0}, {id: 2, x: 19, y: 0}], eye, new Set([1]), true)], [1]);
assert.deepEqual([...chooseDetailedCars([{id: 1, x: 20, y: 0}, {id: 2, x: 8, y: 0}], eye, new Set([1]), true)], [2]);
const phase0 = npcWheelPose({totalMoved: 0, heading: 359});
const phase1 = npcWheelPose({totalMoved: .365, heading: 1}, phase0);
assert.equal(phase1.angle, 1);
assert(phase1.steer > 0 && phase1.steer < .3, 'Heading wrap is a small positive turn');
const stopped = npcWheelPose({totalMoved: .365, heading: 1}, phase1);
assert.equal(stopped.angle, phase1.angle);
assert.equal(stopped.steer, phase1.steer);
const reentry = npcWheelPose({totalMoved: 20, heading: 80});
assert(Math.abs(reentry.angle - 20 / .365 % (2 * Math.PI)) < 1e-12, 'Phase follows persistent distance, never visibility slot');
const report = {passed: true, checks: ['2 desktop / 1 mobile detail caps', '3D distance excludes aerial mesh cost', 'Entry/exit hysteresis and nearer-car replacement', 'Finite eye guard', 'Rolling phase uses accepted travel and freezes on stop', 'Heading wrap and culling re-entry'], scope: 'Pure state tests only; no runtime integration or performance claim'};
fs.writeFileSync('qc/npc-detail-state-test.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
